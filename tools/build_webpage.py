#!/usr/bin/env python3
"""
Builds LapLogic/webpage.h: the board's settings page (tools/web/settings.html with the
shared form from tools/web/form.css + form.js), gzipped, as a byte array the firmware
serves straight from flash.

Run after editing anything in tools/web/:
    python3 tools/build_webpage.py
"""
import gzip
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB = ROOT / "tools" / "web"


def page() -> str:
    html = (WEB / "settings.html").read_text()
    html = html.replace("/*FORM_CSS*/", (WEB / "form.css").read_text())
    html = html.replace("/*FORM_JS*/", (WEB / "form.js").read_text())
    return html


def main() -> None:
    raw = page().encode("utf-8")
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(gz), 20):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
    out = ROOT / "LapLogic" / "webpage.h"
    out.write_text(
        "// Generated by tools/build_webpage.py from tools/web/ - edit those files, not this one.\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        f"static const size_t SETTINGS_PAGE_GZ_LEN = {len(gz)};\n"
        "static const uint8_t SETTINGS_PAGE_GZ[] PROGMEM = {\n" + "\n".join(lines) + "\n};\n")
    print(f"Wrote {out.relative_to(ROOT)}: {len(raw):,} bytes of HTML -> {len(gz):,} gzipped")


if __name__ == "__main__":
    main()
